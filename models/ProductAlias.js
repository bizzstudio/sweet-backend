// models/ProductAlias.js
//
// "איך הלקוח קורא למוצר" → המוצר בקטלוג.
//
// ── למה זה קיים ──
//
// מנוע ההתאמה מדרג שמות לפי דמיון טקסטואלי, ויש שאלות שדמיון טקסטואלי לא
// יכול לענות עליהן. לקוח שכותב "קולה זירו" מתכוון לאחד מארבעה מוצרים בקטלוג
// ("פחיות קולה זירו", "פחיות קולה זירו 24 יח", "קוקה קולה זירו 1 ליטר",
// "קוקה קולה זירו לימון 1.5 ליטר"), ואין בטקסט שכתב שום דבר שמכריע ביניהם.
// גם אדם לא יכול להכריע מהטקסט לבדו — הוא מכריע מתוך *היכרות עם הלקוח*.
//
// עד היום ההיכרות הזו לא נשמרה בשום מקום. עובד היה פותר "קולה זירו" ביד,
// אותו לקוח היה כותב "קולה זירו" למחרת, והשורה הייתה נכשלת שוב — אותה שורה,
// אותה שגיאה, כל יום. המערכת לא נעשתה טובה יותר עם הזמן.
//
// כאן ההכרעה נשמרת. אדם מכריע פעם אחת, ומאותו רגע השורה נקראת אוטומטית.
//
// ── היקף: ללקוח, או לכולם ──
//
// `customer: null` = כלל-מערכתי. אחרת — ללקוח הזה בלבד, והוא גובר.
//
// ההפרדה אינה קוסמטית: "קולה זירו" אצל לקוח אחד הוא מארז הפחיות ואצל אחר
// בקבוק ליטר וחצי. אליאס כלל-מערכתי במקרה כזה היה מכניס לחלק מהלקוחות מוצר
// שהם לא ביקשו — בשקט ובביטחון מלא, וזה הכשל היקר ביותר בצינור הזה. לכן
// ברירת המחדל בממשק היא "ללקוח הזה", והכלל-מערכתי הוא בחירה מפורשת.

const mongoose = require("mongoose");

const productAliasSchema = new mongoose.Schema(
  {
    // הטקסט שהלקוח כתב, מנורמל. הנרמול חייב להיות זהה לזה של מנוע ההתאמה
    // (normalizeTitleForMatch), אחרת השמירה והשליפה יראו מפתחות שונים —
    // ראה utils/productAliases.js, ששולט בשניהם.
    key: { type: String, required: true, trim: true },

    // null = כלל-מערכתי. ראה ההסבר על ההיקף למעלה.
    customer: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Customer",
      default: null,
    },

    // ריק כשההכרעה היא "זו אינה שורת מוצר" (ignore).
    //
    // באליאס של כמה מוצרים זה תמיד המוצר הראשון ברשימה `products`. השדה
    // נשמר מלא גם אז כדי שכל קוד שקורא רק אותו (רשומות שנשמרו לפני שהיו כמה
    // מוצרים, האינדקס "כל האליאסים של מוצר") ימשיך לראות מוצר אמיתי.
    product: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Product",
      required: function () {
        return !this.ignore;
      },
      default: null,
    },

    // ── שורה אחת של הלקוח, כמה מוצרים בקטלוג ──
    //
    // לקוח כותב "חד פעמי סכו"ם וצלחות", ובקטלוג אין מוצר כזה — יש מזלגות,
    // סכינים, כפות, צלחות גדולות וצלחות קטנות. ההכרעה האנושית כאן אינה "איזה
    // מוצר" אלא "אילו מוצרים", והקליטה פורשת את השורה לכל אחד מהם.
    //
    // כל מוצר נכנס בכמות שהלקוח כתב בשורה. ‏quantity נשמר תמיד null: כמות
    // קבועה נשקלה ונדחתה — המנהלת (28/10/26): "פעם שלושה שרוולים, פעם עשרה,
    // בשום דבר זה לא קבוע". השדה נשאר כדי שלא לשנות שוב את מבנה הרשומה.
    //
    // רשומות ישנות לא מחזיקות את השדה כלל (רק `product`). כל קריאה עוברת דרך
    // aliasEntries ב-utils/productAliases, שמתייחסת לשתי הצורות כאחת.
    products: {
      type: [
        {
          product: { type: mongoose.Schema.Types.ObjectId, ref: "Product", required: true },
          quantity: { type: Number, default: null, min: 0 },
          _id: false,
        },
      ],
      default: undefined,
    },

    // "זו אינה שורת מוצר": כותרת, שאלה, שם של עובד. השורה יורדת להערת ההזמנה
    // בכל פעם שהלקוח כותב אותה, במקום לעצור את ההזמנה שוב.
    ignore: { type: Boolean, default: false },

    // הטקסט המקורי לפני נרמול — מוצג בממשק הניהול. `key` אינו קריא לאדם
    // ("קולה זירו" ו-"קולה  זירו!" מתמפים לאותו מפתח), ובלי המקור אי אפשר
    // להבין למה אליאס נוצר.
    sourceName: { type: String, required: false },

    createdBy: { type: String, required: false },

    // כמה פעמים האליאס חסך הכרעה אנושית. זה גם המדד לשאלה "האם המנגנון
    // מתכנס" וגם מה שמאפשר לנקות אליאסים שנוצרו בטעות ואיש לא נגע בהם.
    hits: { type: Number, default: 0 },
    lastUsedAt: { type: Date, required: false },
  },
  { timestamps: true }
);

// ── למה ייחודי, ולמה על שני השדות ──
//
// שתי רשומות לאותו (מפתח, לקוח) פירושן ששני מוצרים שונים תובעים את אותו שם,
// והבחירה ביניהם הייתה נקבעת לפי סדר השליפה — כלומר המערכת הייתה מכניסה
// מוצר אחר בכל פעם. עדכון גובר על יצירה (upsert ב-saveAlias).
//
// ‏mongo מתייחס ל-null כערך לכל דבר, ולכן רשומה כלל-מערכתית אחת לכל מפתח
// נאכפת כאן בדיוק כמו רשומה ללקוח.
productAliasSchema.index({ key: 1, customer: 1 }, { unique: true });

// שליפת כל האליאסים של מוצר — נדרש כשמוצר נמחק או מוחלף
productAliasSchema.index({ product: 1 });
productAliasSchema.index({ "products.product": 1 });

// רשימת האליאסים של לקוח — לכרטיס הלקוח (ראה controller/productAliasController)
productAliasSchema.index({ customer: 1, updatedAt: -1 });

const ProductAlias = mongoose.model("ProductAlias", productAliasSchema);

module.exports = ProductAlias;
