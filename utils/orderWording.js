// אותו דבר, מילים אחרות.
//
// ── מה זה פותר ──
//
// לקוח מזמין בשפה שלו, והקטלוג כתוב בשפה של ההנהח"ש:
//
//     "חלב 3 אחוז"      בקטלוג "חלב טרי 3%"
//     "סוכר קילו"        בקטלוג 'סוכר 1 ק"ג בשקית'
//     "עוגיות בקופסא"    בקטלוג "עוגיות בקופסה"
//     "ביצים 30 יחידות"  בקטלוג "ביצים 30 יח"
//
// אלה **אינן עמימות** — זה אותו מוצר בדיוק, במילה אחרת. בלי הנרמול הזה כל
// אחת מהן נראית כשורה שלא מתארת מוצר, ומגיעה לאדם או יורדת להערה.
//
// ── למה זה לא נכנס ל-normalizeTitleForMatch ──
//
// זו הפונקציה שמייצרת את **מפתח האליאס** (utils/productAliases). שינוי שלה
// משנה את המפתח של כל אליאס שנשמר אי פעם — ומאותו רגע הכרעות אנושיות שנשמרו
// לא יימצאו לעולם. כשל שקט לחלוטין: הממשק מראה שהאליאס קיים, והקליטה ממשיכה
// להיכשל על אותה שורה. לכן זו שכבה נפרדת שמוחלת רק במקומות שבוחרים בה.
//
// ── מה זה **לא** עושה ──
//
// זה אינו קובע **איזה** מוצר נבחר — רק אם השורה מתארת מוצר בכלל. הבחירה
// נשארת אצל מנוע ההתאמה, מזהי הגרסה וההיסטוריה.

const { normalizeTitleForMatch } = require("./productMatching");

// ── מילות מידה ואריזה: צורה קנונית אחת ──
//
// מחרוזת ריקה = המילה נמחקת. "אחוז" הוא המקרה הבולט: בקטלוג הוא נכתב כ-%,
// ו-normalizeTitleForMatch מסירה סימנים — כלומר בצד הקטלוג הוא כבר לא קיים,
// ורק בצד הלקוח הוא נשאר.
const SYNONYMS = new Map(
  Object.entries({
    אחוז: "", אחוזים: "", אחוזי: "",
    קילו: "קג", קילוגרם: "קג", קילוגרמים: "קג",
    גרם: "גר", גרמים: "גר",
    ליטרים: "ליטר",
    יחידות: "יח", יחידה: "יח", יחידת: "יח",
    חבילה: "מארז", חבילות: "מארז", מארזים: "מארז",
    בקבוקים: "בקבוק", כוסיות: "כוס", גליל: "גלילים",
    // צורות סמיכות שלקוחות כותבים ושם המוצר אינו נושא: "שישיית מי עדן" מול
    // "מי עדן 1.5 ליטר שישיה" (נמדד 11/10/26 — השורה הותאמה ל"מעדן באדי")
    שישיית: "שישיה", שישייה: "שישיה", שישיות: "שישיה",
    שלישיית: "שלישיה", שלישייה: "שלישיה",
    חבילת: "מארז", קופסת: "קופסה", קופסא: "קופסה", בקבוקי: "בקבוק",
    // "קפה שחור" ו"קפה טורקי" הם אותו מוצר; הקטלוג כותב "טורקי" והלקוחות "שחור"
    טורקי: "שחור",
    // ── אותו מוצר בשם אחר (נבדק מול אקסל ההיסטוריה, 11/10/26) ──
    // בילטון כתבה "פלפלים אדומים" ובאקסל שלה "גמבה אדומה 1 קילו"
    גמבה: "פלפל", גמבות: "פלפל",
    // כתיב: באקסל "גבינת שמנת נפולאון" ו"נס קפה גקובס"
    נפולאון: "נפוליאון", גייקובס: "גקובס", גיקובס: "גקובס", יעקובס: "גקובס",
  })
);

// ── סיומת א' במקום ה' ──
//
// כתיב נפוץ בהזמנות: "בקופסא", "קופסא", "מנא". הכלל גנרי ולא רשימה, והוא
// בטוח כאן דווקא משום שהוא מוחל על **שני** הצדדים: אם גם הקטלוג נורמל כך,
// ההשוואה נשארת עקבית ומילה שאינה קיימת בקטלוג לא הופכת פתאום לקיימת.
// ── רק על מילים ארוכות ──
//
// נמדד על 3,045 המילים שבקטלוג: הכלל מיזג 54 קבוצות, וכולן כתיב שונה של אותה
// מילה בדיוק (`קופסא`/`קופסה`, `ניילון`/`נילון`, `שלישייה`/`שלישיה`) — חוץ
// מאחת: `לא` הפכה ל-`לה`. מילים קצרות הן לרוב מילות קישור, ובהן הסיומת אינה
// כתיב חלופי אלא המילה עצמה.
//
// הגבול נבחר לפי המדידה: 4 תווים שומר על **כל** המיזוגים הנכונים ומבטל את
// היחיד השגוי.
const MIN_ALEF_SUFFIX_LENGTH = 4;

const finalAlefToHe = (word) =>
  word.length >= MIN_ALEF_SUFFIX_LENGTH && /א$/.test(word)
    ? `${word.slice(0, -1)}ה`
    : word;

// ── יו"ד כפולה ──
//
// "שישיה" מול "שישייה", "שניה" מול "שנייה" — כתיב מלא וחסר של אותה מילה.
// כלל גנרי במקום רשימה, ובטוח מאותה סיבה כמו הסיומת: הוא מוחל על שני הצדדים,
// ולכן אינו יוצר התאמות שלא היו קיימות אלא רק מיישר כתיב.
const collapseDoubleYod = (word) => word.replace(/יי/g, "י");

const canonicalWord = (word) => {
  const mapped = SYNONYMS.get(word);
  if (mapped !== undefined) return mapped;
  return collapseDoubleYod(finalAlefToHe(word));
};

/**
 * מילות הטקסט בצורתן הקנונית, בלי מילים בנות תו אחד.
 *
 * מוחל על שני הצדדים — שאילתת הלקוח ושם המוצר — אחרת הנרמול רק היה מזיז את
 * הפער במקום לסגור אותו.
 */
// ── צירופים שהם שם אחר לאותו מוצר ──
//
// מילה בודדת אינה מספיקה כאן: "כסף" ו"ידיים" אינם נרדפים לשום דבר, אבל
// "נייר כסף" הוא נייר אלומיניום ו"נייר ידיים" הוא נייר צץ רץ. נמדד מול
// האקסל: אמזה כתבה "נייר כסף" וקונה "נייר אלומיניום קצר" (18 פעמים); אורט
// כתבה "נייר ידיים" וקונה "נייר צץ רץ" (154 פעמים).
// הדפוסים סובלים יו"ד כפולה בעצמם ("נייר"/"ניר", "ידיים"/"ידים"). כיווץ של
// הטקסט כולו לפני החלוקה למילים היה שובר את טבלת הנרדפות, שמפתחותיה נכתבים
// בכתיב המלא ("שישיית").
const PHRASES = [
  [/ני{1,2}ר כסף/g, "נייר אלומיניום"],
  [/מגבות? ני{1,2}ר לידי{1,2}ם/g, "נייר צץ רץ"],
  [/ני{1,2}ר ידי{1,2}ם/g, "נייר צץ רץ"],
];

const withPhrases = (normalized) =>
  PHRASES.reduce((text, [from, to]) => text.replace(from, to), normalized);

const canonicalWords = (text) =>
  withPhrases(normalizeTitleForMatch(text))
    .split(" ")
    .map(canonicalWord)
    .filter((word) => word.length > 1);

module.exports = { canonicalWords, canonicalWord };
