// script/test-catalog-vocabulary.js
//
// בדיקת האות "האם השורה מתחום המוצרים" — הרצה: npm run vocab:test
//
// ── מה נשמר כאן ──
//
// שורה בלי כמות שלא כוסתה במלואה עומדת בפני שתי אפשרויות: לרדת להערת ההזמנה
// (וההזמנה נשלחת בלעדיה, בשקט) או להגיע לאדם. ההכרעה ביניהן נעשית לפי תדירות
// המילה בקטלוג, וטעות כאן היא או פריט שנעלם מהמשלוח או הזמנה שנופלת מדיבור.
//
// הבדיקה טהורה — אוצר המילים מוזרק ואינה נוגעת במסד.

const {
  productWordFraction,
  looksLikeProductAttempt,
  MIN_PRODUCT_WORD_STRENGTH,
  MIN_PRODUCT_WORD_FRACTION,
} = require("../utils/catalogVocabulary");

let passed = 0;
const failures = [];

const check = (label, actual, expected) => {
  if (actual === expected) {
    passed += 1;
    console.log(`  ✓ ${label}`);
    return;
  }
  failures.push(`${label} — ציפינו "${expected}", התקבל "${actual}"`);
  console.log(`  ✗ ${label}\n      ציפינו: ${expected}\n      התקבל:  ${actual}`);
};

const section = (title) => console.log(`\n── ${title} ──`);

// ── האוצר נבנה כמו שהקוד בונה אותו ──
//
// ‏productWordStrength מנרמל את השאילתה לצורה קנונית (utils/orderWording),
// ולכן מפתח בכתיב גולמי לא יימצא: "נייר" מתנרמל ל-"ניר". בניית המפה כאן
// באותה דרך היא מה שמונע מהבדיקה לבדוק מפתחות שהקוד לעולם לא מחפש.
const { canonicalWord } = require("../utils/orderWording");

// התדירויות האמיתיות שנמדדו על הקטלוג (4,320 מוצרים)
const VOCAB = new Map(
  Object.entries({
    נייר: 156, קילו: 157, תה: 148, כוסות: 91, שוקולד: 83, קפה: 81,
    לכוסות: 5, קלסר: 61, עוגיות: 50, חלב: 41, בננות: 12, מים: 12,
    טורקי: 4, מגבות: 9, מכסה: 7, אגסים: 8,
    משרדי: 22, גדול: 61, חד: 61, פעמי: 77, טואלט: 30, גלילים: 19,
    בקופסה: 48, לכוסות: 5, מכסים: 1, צמחים: 8, שקיקים: 1,
    סליחה: 0, ההפרעה: 0,
    // מילים שביטויי שיחה חולקים עם הקטלוג במקרה
    מה: 1, סבבה: 1, טוב: 1, מתי: 1, על: 8, שמח: 1,
    // מספרים: התדירויות האמיתיות בקטלוג. הן מה ששבר את הניסוח הקודם —
    // "קומה 3 דירה 12" קיבלה חוזק 28 מ-"12" ונשלחה לאדם במקום להערה.
    "12": 28, "30": 19, "50": 104, "100": 148, "10": 41,
    // מילות כתובת ושיחה שאינן בקטלוג
    קומה: 0, דירה: 0, שנייה: 0, שכחתי: 0,
  }).map(([word, count]) => [canonicalWord(word), count])
);

const attempt = (text) => looksLikeProductAttempt(text, VOCAB);

// ───────────────────────────────────────────────────────────────

section("מוצר אמיתי בניסוח חופשי — חייב להגיע לאדם, לא להערה");

// אלה בדיוק המקרים שירדו להערה וההזמנה נשלחה בלעדיהם
[
  "חלב 3 אחוז",        // בקטלוג "חלב טרי 3%"
  "עוגיות בקופסא",     // כתיב
  "קפה טורקי 200 גרם",
  "מגבות נייר שישיה",
  "קלסר משרדי גדול",
  "אגסים קילו",
  "מכסים לכוסות",      // המילה החלשה ביותר שנמדדה (5)
].forEach((line) => check(`"${line}"`, attempt(line), true));

section("שיחה — יורדת להערה");

[
  "שנייה", "חכי", "תכף", "בעצם", "אולי", "נראה לי", "שכחתי",
  "זהו זה", "יאללה", "אני חושבת", "תני לי לבדוק", "תעדכן אותי",
  "מה המצב", "מה נשמע", "סבבה גמור", "נו טוב", "מתי מגיע",
].forEach((line) => check(`"${line}"`, attempt(line), false));

section("מספרים אינם מעידים על מוצר");

// ── הבאג שנמצא בסקירה ──
//
// "12" מופיע ב-28 שמות מוצר, "50" ב-104 ו-"100" ב-148. הניסוח הקודם בדק את
// **המילה החזקה** בשורה, ולכן `קומה 3 דירה 12` קיבלה 28 ונשלחה לאדם במקום
// לרדת להערה — שורת כתובת שמפילה הזמנה.
//
// מספרים משמעותיים לזיהוי **איזה** מוצר (coversAllWords כן סופר אותם), אבל
// אינם מעידים שהשורה היא מתחום המוצרים.
check('"קומה 3 דירה 12" אינה מוצר', attempt("קומה 3 דירה 12"), false);
check('"דירה 12" אינה מוצר', attempt("דירה 12"), false);
check("מספרים בלבד אינם מוצר", attempt("12 50 100"), false);
check(
  "מספר אינו מציל שורת שיחה",
  attempt("שכחתי 100"),
  false
);
// אבל מילת מוצר אמיתית לצד מספר כן
check('"חלב 3 אחוז" כן מוצר', attempt("חלב 3 אחוז"), true);

section("הגבול, ולאיזה כיוון הוא נוטה");

// ── למה דווקא לכיוון האדם ──
//
// בטווח החפיפה (נמדד: מוצרים מ-5, שיחה עד 8) אין הפרדה מושלמת. הכיוון נבחר
// לפי מחיר הטעות: שורת שיחה שנשלחת לבדיקה עולה מבט אחד, ופריט אמיתי שיורד
// להערה נשלח חסר ואיש לא יודע.
// ── מה שהשיעור תיקן ──
//
// בניסוח הקודם (שיא במקום שיעור) השורה הזו קיבלה 8 מ-"על" ונשלחה לאדם. עם
// שיעור היא 1 מתוך 3 — 33%, מתחת לסף — ויורדת להערה, כפי שצריך.
check(
  '"סליחה על ההפרעה" — מילת קישור אחת אינה הופכת שורה למוצר',
  attempt("סליחה על ההפרעה"),
  false
);
// ‏"מכסים לכוסות" הוא הנמוך ביותר מבין המוצרים שנמדדו: "מכסים" מופיע במוצר
// אחד ו-"לכוסות" בחמישה. הוא בדיוק על הסף, ולכן הוא הבדיקה שנשברת ראשונה
// אם מישהו יעלה אותו.
check('"מכסים לכוסות" — המוצר החלש ביותר שנמדד', attempt("מכסים לכוסות"), true);
check(`מילה בדיוק בסף (${MIN_PRODUCT_WORD_STRENGTH} מוצרים)`, attempt("טורקי"), true);
check("מילה מתחת לסף", attempt("מה"), false);
check(
  `שיעור בדיוק בסף (${MIN_PRODUCT_WORD_FRACTION})`,
  productWordFraction("חלב שכחתי", VOCAB),
  0.5
);

section("מקרי קצה");

// ── נעילה: הצורה הקנונית משותפת לשני הצדדים ──
//
// אם השאילתה תנורמל והקטלוג לא (או להפך), אף מילה לא תימצא והאות ישתתק
// לגמרי — בשקט. שתי הבדיקות האלה נכשלות ברגע שמישהו מנרמל רק בצד אחד.
check("\"קילו\" ו-\"קג\" הן אותה מילה", canonicalWord("קילו"), canonicalWord("קג"));
check("\"שישיה\" ו-\"שישייה\" הן אותה מילה", canonicalWord("שישיה"), canonicalWord("שישייה"));
check("\"בקופסא\" ו-\"בקופסה\" הן אותה מילה", canonicalWord("בקופסא"), canonicalWord("בקופסה"));
check("\"אחוז\" נמחקת", canonicalWord("אחוז"), "");

// ── מילים קצרות אינן מנורמלות בסיומת ──
//
// נמדד על 3,045 מילות הקטלוג: הכלל מיזג 53 קבוצות, כולן כתיב שונה של אותה
// מילה — חוץ מ-"לא" שהפכה ל-"לה". מילים קצרות הן לרוב מילות קישור, ושם
// הסיומת אינה כתיב חלופי אלא המילה עצמה.
check('"לא" נשארת "לא"', canonicalWord("לא"), "לא");
check('"בא" נשארת "בא"', canonicalWord("בא"), "בא");
check('"קופסא" כן מנורמלת', canonicalWord("קופסא"), canonicalWord("קופסה"));

check("שורה ריקה", attempt(""), false);
check("מספרים בלבד", attempt("3 5"), false);
check("בלי אוצר מילים כלל — לא קורס", looksLikeProductAttempt("חלב", null), false);
check("שיעור מלא כשכל המילים בקטלוג", productWordFraction("נייר כוסות", VOCAB), 1);
check("אפס כשאף מילה אינה בקטלוג", productWordFraction("קסדרלימ טרפוזין", VOCAB), 0);
check("בלי אוצר מילים מחזיר אפס", productWordFraction("חלב", null), 0);

// ───────────────────────────────────────────────────────────────

console.log(`\n${"─".repeat(50)}`);
if (failures.length) {
  console.log(`נכשלו ${failures.length} בדיקות מתוך ${passed + failures.length}:`);
  failures.forEach((f) => console.log(`  • ${f}`));
  process.exit(1);
}
console.log(`כל ${passed} הבדיקות עברו.`);
