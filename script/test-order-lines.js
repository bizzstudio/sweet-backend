// script/test-order-lines.js
//
// בדיקת קריאת שורות פריט מהודעת ווצאפ — הרצה: npm run ingest:lines-test
//
// ── למה זה קיים ──
//
// שתי תקלות שנמדדו בהזמנה אמיתית אחת, ושתיהן שקטות:
//
//   "ו3 אגסים"  →  נקרא כפריט אחד בשם "ו3 אגסים"   (הלקוח ביקש שלושה)
//   "אה ורגע"   →  נקרא כשם מוצר                    (זו מילת מילוי)
//
// הראשונה משנה כמות במשלוח. השנייה גרועה יותר: הביטחון הכולל של ההזמנה הוא
// ה**מינימום** מבין הפריטים, ולכן שתי מילות מילוי הפילו הזמנה עם ארבעה
// פריטים תקינים ל"לא הובנה במלואה".

const { parseOrderText } = require("../lib/order-ingestion/tableParser");

let passed = 0;
const failures = [];

const check = (label, actual, expected) => {
  const same = JSON.stringify(actual) === JSON.stringify(expected);
  if (same) {
    passed += 1;
    console.log(`  ✓ ${label}`);
    return;
  }
  failures.push(`${label} — ציפינו ${JSON.stringify(expected)}, התקבל ${JSON.stringify(actual)}`);
  console.log(`  ✗ ${label}\n      ציפינו: ${JSON.stringify(expected)}\n      התקבל:  ${JSON.stringify(actual)}`);
};

const section = (title) => console.log(`\n── ${title} ──`);

const parse = (lines) =>
  parseOrderText({
    text: [].concat(lines).join("\n"),
    channel: "whatsapp",
    sender: { phone: "0500000000" },
  });

// ── למה הבדיקה עוטפת את השורה בהודעה עם פריט נוסף ──
//
// הפרסר מסווג קודם "האם זו הזמנה בכלל", ושורה בודדת אינה חוצה את הסף. בלי
// העטיפה כל בדיקה כאן הייתה מודדת את המסווג במקום את קריאת השורה.
const ANCHOR = "2 חלב";

// השורה הנבדקת → { שם, כמות }, או null אם לא נקראה כפריט
const one = (line) => {
  const items = parse(["הזמנה", ANCHOR, line])?.items || [];
  const item = items.find((i) => i.rawName !== "חלב");
  return item ? { name: item.rawName, qty: item.quantity } : null;
};

// ───────────────────────────────────────────────────────────────

section("ו' החיבור הדבוקה לכמות");

// כך מונים בווצאפ: "5 קלסר / ו3 אגסים". בלי זה 3 אגסים הפכו ל-1, והשם
// שנשלח לחיפוש היה "ו3 אגסים" — עם "ו3" כמילה שמרעילה את השאילתה
check('"ו3 אגסים" נקרא כשלושה', one("ו3 אגסים"), { name: "אגסים", qty: 3 });
check('"ו 3 אגסים" עם רווח', one("ו 3 אגסים"), { name: "אגסים", qty: 3 });
check('"3 אגסים" ללא ו — כמו קודם', one("3 אגסים"), { name: "אגסים", qty: 3 });
check('"5 קלסר"', one("5 קלסר"), { name: "קלסר", qty: 5 });

// ── מה שאסור להישבר ──
//
// ‏ו' היא אות, לא סימן פיסוק. אילו הוכנסה למחלקת התווים של התבליטים היא
// הייתה מוחקת אות פותחת משמות מוצרים.
check(
  "שם מוצר שמתחיל ב-ו לא נחתך",
  one("2 וופל בלגי"),
  { name: "וופל בלגי", qty: 2 }
);
check(
  "שם שמתחיל ב-ו גם בלי כמות",
  one("וופל בלגי"),
  { name: "וופל בלגי", qty: 1 }
);
// ── "1.5 ליטר" היא מידה, לא כמות ──
//
// הלקוח שכתב "1.5 ליטר קולה" ביקש בקבוק אחד של ליטר וחצי, לא ליטר וחצי
// בקבוקים. הפרסר מזהה את הצירוף מספר+יחידת מידה ומשאיר אותו בשם — וזו
// ההתנהגות הנכונה. אילו ה-1.5 הייתה נקראת ככמות, "קולה" הייתה מחפשת בלי
// המידה שמבדילה בין 1 ל-1.5 ליטר.
check(
  "מספר שצמוד ליחידת מידה נשאר בשם",
  one("1.5 ליטר קולה"),
  { name: "1.5 ליטר קולה", qty: 1 }
);
check('"3. עוגיות" — מספור נקרא ככמות', one("3. עוגיות"), { name: "עוגיות", qty: 3 });

section("מילות מילוי בשיחה");

// הביטחון הכולל הוא המינימום מבין הפריטים — מילת מילוי אחת מפילה הזמנה שלמה
const filler = ["אה ורגע", "כן רגע", "רגע", "אוקי", "כן", "בסדר", "אחלה"];
filler.forEach((line) =>
  check(`"${line}" אינה פריט`, one(line), null)
);

// ── הגבול ──
//
// ההתאמה היא לשורה **שלמה** שכולה מילות מילוי. שורה שיש בה גם מילים אמיתיות
// היא שורת פריט לכל דבר, גם כשהיא פותחת ב-"לא".
check(
  '"לא תה ירוק" נשארת שורת פריט',
  Boolean(one("לא תה ירוק")),
  true
);
check('"3 רגע אדום" נשארת פריט', one("3 רגע אדום"), { name: "רגע אדום", qty: 3 });

section("ההזמנה שנמדדה, מקצה לקצה");

const real = parse([
  "הזמנה חדשה",
  "מכסה לכוסות",
  "עוגיות בקופסה",
  "תודה רבה",
  "אה ורגע",
  "5 קלסר",
  "ו3 אגסים",
  "כן רגע",
]);

check(
  "ארבעה פריטים, בלי מילות מילוי",
  real.items.map((i) => `${i.rawName}×${i.quantity}`),
  ["מכסה לכוסות×1", "עוגיות בקופסה×1", "קלסר×5", "אגסים×3"]
);
check(
  "וארבע שורות דולגו",
  (real.skippedRows || []).map((r) => r.raw),
  ["הזמנה חדשה", "תודה רבה", "אה ורגע", "כן רגע"]
);

// ───────────────────────────────────────────────────────────────

section("עמידות: הרגקסים רצים על קלט לא מהימן");

// ── למה זה נבדק ──
//
// כל שורה בכל הודעה נכנסת עוברת דרך הדפוסים האלה, והודעת ווצאפ מותרת עד
// 40,000 תווים. רגקס עם backtracking ריבועי כאן אינו אי-יעילות אלא **וקטור
// חסימה**: הודעה אחת תופסת את הצינור.
//
// זה קרה בפועל בגרסה הראשונה של התיקון: הצירוף `\s*ו?\s*` — שני `\s*` משני
// צדי אופציונלי — מייצר n דרכים לחלק רצף רווחים. נמדד 27ms על 5,000 רווחים
// ו-407ms על 20,000. הניסוח `(?:ו\s*)?` חוסם את הפיצול ורץ לינארית.
const timed = (fn) => {
  const started = process.hrtime.bigint();
  fn();
  return Number(process.hrtime.bigint() - started) / 1e6;
};

// התקרה נדיבה בכוונה: היא תופסת התדרדרות ריבועית (מאות אלפי ms) ולא רגישה
// לרעש של מכונה עמוסה
const BUDGET_MS = 250;

const HOSTILE = [
  ["רצף רווחים", " ".repeat(40000) + "X"],
  ["רצף ו'", "ו".repeat(40000) + "X"],
  ["מילת מילוי + רווחים", "רגע" + " ".repeat(40000) + "X"],
  ["מילות מילוי חוזרות", "לא רגע כן ".repeat(4000) + "X"],
  ["אה + הא ארוך", "א" + "ה".repeat(40000) + "X"],
  ["ספרה + טקסט ארוך", "3 " + "א".repeat(40000)],
];

HOSTILE.forEach(([label, text]) => {
  const ms = timed(() => parse(["הזמנה", "2 חלב", text]));
  check(
    `${label} (${text.length} תווים) מתחת ל-${BUDGET_MS}ms`,
    ms < BUDGET_MS,
    true
  );
});

// ───────────────────────────────────────────────────────────────

section("הרשימה כאן היא קיצור דרך — לא ההגנה");

// ── חלוקת התפקידים ──
//
// הפרסר מדלג רק על מה שברשימה: ברכות ומילות מילוי מוכרות. הוא **לא** יודע
// מה יש בקטלוג, ולכן "שנייה" או "מה המצב" ממשיכות ממנו כשורות פריט.
//
// מי שעוצר אותן הוא `resolveItems`: שורה בלי כמות נכנסת להזמנה רק אם כל מילה
// בה נמצאת בשם של מוצר בקטלוג (`coversAllWords`). נמדד מול הקטלוג המלא —
// 60 ביטויי שיחה, אחד בלבד נמצא מכוסה ("חג שמח", שנוסף כאן לברכות); 67 שמות
// מוצר אמיתיים, אף אחד לא נפסל.
//
// לכן הבדיקות כאן מכסות את הרשימה בלבד. ההגנה עצמה נבדקת ב-history:test
// (‏coversAllWords) וב-history:pipeline-test (‏droppedAsText מקצה לקצה).
[
  "רגע", "כן", "אוקי", "בסדר", "אחלה", "אה ורגע", "כן רגע",
  "חג שמח", "שבת שלום", "שבוע טוב",
].forEach((line) => check(`"${line}" מדולגת בפרסר`, one(line), null));

// ── והצד השני: מה שאסור לאבד ──
//
// שורה בלי כמות שכן מתארת מוצר היא הצורה הנפוצה ביותר להזמין בווצאפ, והיא
// חייבת להמשיך מהפרסר הלאה.
[
  ["מגבות נייר", 1],
  ["עוגיות בקופסה", 1],
  ["מכסה לכוסות", 1],
  ["קלסר", 1],
].forEach(([line, qty]) =>
  check(`"${line}" ממשיכה כשורת פריט`, one(line), { name: line, qty })
);

// ───────────────────────────────────────────────────────────────

console.log(`\n${"─".repeat(50)}`);
if (failures.length) {
  console.log(`נכשלו ${failures.length} בדיקות מתוך ${passed + failures.length}:`);
  failures.forEach((f) => console.log(`  • ${f}`));
  process.exit(1);
}
console.log(`כל ${passed} הבדיקות עברו.`);
