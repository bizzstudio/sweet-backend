section("עמידות: הרגקסים רצים על קלט לא מהימן");

// ── למה זה נבדק ──
//
// כל שורה בכל הודעה נכנסת עוברת דרך הדפוסים האלה, והודעת ווצאפ מותרת עד
// 40,000 תווים. רגקס עם backtracking ריבועי כאן אינו אי-יעילות אלא **וקטור
// חסימה**: הודעה אחת תופסת את הצינור.
//
// זה קרה בפועל בגרסה הראשונה של התיקון: הצירוף `\s*ו?\s*` — שני `\s*` משני
// צדי אופציונלי — מייצר n דרכים לחלק רצף רווחים. נמדד 27ms על 5,000 רווחים
// ו-407ms על 20,000. הניסוח `(?:ו\s*)?` חוסם את הפיצול ורץ לינארית.
const timed = (fn) => {
  const started = process.hrtime.bigint();
  fn();
  return Number(process.hrtime.bigint() - started) / 1e6;
};

// התקרה נדיבה בכוונה: היא תופסת התדרדרות ריבועית (מאות אלפי ms) ולא רגישה
// לרעש של מכונה עמוסה
const BUDGET_MS = 250;

const HOSTILE = [
  ["רצף רווחים", " ".repeat(40000) + "X"],
  ["רצף ו'", "ו".repeat(40000) + "X"],
  ["מילת מילוי + רווחים", "רגע" + " ".repeat(40000) + "X"],
  ["מילות מילוי חוזרות", "לא רגע כן ".repeat(4000) + "X"],
  ["אה + הא ארוך", "א" + "ה".repeat(40000) + "X"],
  ["ספרה + טקסט ארוך", "3 " + "א".repeat(40000)],
];

HOSTILE.forEach(([label, text]) => {
  const ms = timed(() => parse(["הזמנה", "2 חלב", text]));
  check(
    `${label} (${text.length} תווים) מתחת ל-${BUDGET_MS}ms`,
    ms < BUDGET_MS,
    true
  );
});

