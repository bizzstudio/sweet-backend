section("כמות עם יחידה (הזמנות 04/10/26)");

// #140221: "במבה- 3 יח" נקרא ככמות 1 והותאם ל"מעטפות 100 יח'"
const unitOf = (line) => {
  const item = (parse(["הזמנה", ANCHOR, line])?.items || []).find((i) => i.rawName !== "חלב");
  return item ? { name: item.rawName, qty: item.quantity, unit: item.unit } : null;
};
check('"במבה- 3 יח"', unitOf("במבה- 3 יח"), { name: "במבה", qty: 3, unit: null });
check('"לחם חמניות-2 יחידות"', unitOf("לחם חמניות-2 יחידות"), { name: "לחם חמניות", qty: 2, unit: null });
check('"3 יח במבה" — היחידה לא נכנסת לשם', unitOf("3 יח במבה"), { name: "במבה", qty: 3, unit: null });
check('"3 יחידות במבה"', unitOf("3 יחידות במבה"), { name: "במבה", qty: 3, unit: null });
check('"3 יח׳ במבה" עם גרש עברי', unitOf("3 יח׳ במבה"), { name: "במבה", qty: 3, unit: null });
// קילו **אינו** כמות: 5 × "מלפפון 1 ק"ג" או 1 × "מלפפון 5 ק"ג"? המידה נשארת
// בשם, ומזהי הגרסה מכריעים לפיה או עוצרים לאדם
check('"מלפפון- 5 קילו" — המידה נשארת בשם', one("מלפפון- 5 קילו"), { name: "מלפפון- 5 קילו", qty: 1 });
check(
  "כמות מ-\"N יח\" מסומנת לתיקון מארז",
  (parse(["הזמנה", ANCHOR, "פחיות קולה - 24 יח"])?.items || []).find((i) => i.rawName !== "חלב")?.countUnit,
  true
);
// בלי מפריד זו מידת המוצר — בקטלוג יש "ביצים 30 יח"
check('"ביצים 30 יח" נשאר שם מוצר', one("ביצים 30 יח"), { name: "ביצים 30 יח", qty: 1 });

section("כמות בסוף השורה ברשימה");

// #140225: כל ההזמנה נכתבה "שם מספר", וכל שורה נקלטה ככמות 1
const list = parse(["שלום", "חלב רגיל 2", "מעדנים פירות 4", "לחם חום 1"])?.items || [];
check(
  "רשימת 'שם מספר' נקראת ככמויות",
  list.map((i) => [i.rawName, i.quantity]),
  [["חלב רגיל", 2], ["מעדנים פירות", 4], ["לחם חום", 1]]
);
check(
  "פריט מרשימה מסומן כ'כמות שהוסקה'",
  list.every((i) => i.quantityFromTrailing === true && !i.quantityAssumed),
  true
);
// שורה שדפוס מפורש קורא אינה נספרת כראיה לרשימה — אחרת הכתובת הייתה לפריט
check(
  '"חלב x 2" + "הרצל 13" אינם מדליקים את כלל הרשימה',
  (parse(["הזמנה", "חלב x 2", "הרצל 13"])?.items || []).map((i) => [i.rawName, i.quantity]),
  [["חלב", 2], ["הרצל 13", 1]]
);
// כמות מיחידת מכירה: "שם – N חבילות" (11/10/26)
check(
  '"מגבונים – 10 חבילות", "נייר צץ רץ – חבילה", ו"3 חלב - 2 שקיות" נשאר 3',
  (parse(["מגבונים – 10 חבילות", "נייר צץ רץ – חבילה", "3 חלב - 2 שקיות", "בייגלה - 3 קרטונים", "2 במבה"])?.items || []).map((i) => [i.rawName, i.quantity, Boolean(i.quantityAssumed)]),
  [["מגבונים", 10, false], ["נייר צץ רץ", 1, false], ["חלב - 2 שקיות", 3, false], ["בייגלה - 3 קרטונים", 1, true], ["במבה", 2, false]]
);
check(
  '"פג תוקף" כהוראה על פריט אינו מוחק את השורה',
  (parse(["10 חלב לא פג תוקף", "2 במבה"])?.items || []).map((i) => i.quantity),
  [10, 2]
);
// החתימה שלנו עצמנו, ברכת יום ובקשת זיכוי אינן פריט (11/10/26)
check(
  "החתימה שלנו, ברכה ובקשת זיכוי מדולגות",
  (parse(["3 חלב", "יום טוב", '*מתוקיה של בני בע"מ*', "כנרת 13, בני-ברק", "חלב סויה פג תוקף - אנא לזכות", "5 לחם אחיד"])?.items || []).map((i) => [i.rawName, i.quantity]),
  [["חלב", 3], ["לחם אחיד", 5]]
);
// שורה בודדת כזו אינה רשימה — "יום אף 5" הוא שם מוצר
check('"יום אף 5" לבדה אינה כמות', one("יום אף 5"), { name: "יום אף 5", qty: 1 });
check(
  "מספר גדול מ-20 אינו כמות בסוף שורה",
  (parse(["הזמנה", ANCHOR, "שוקולד 100", "ופל 70"])?.items || []).filter((i) => i.rawName !== "חלב").map((i) => i.quantity),
  [1, 1]
);

section("כותרות מייל מועבר");

