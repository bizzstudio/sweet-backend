// script/test-order-table-guard.js
//
// בדיקת ההגנה "טבלה שנקראה — ואינה הזמנה". הרצה: npm run ingest:guard-test
//
// ── למה זה קיים כסקריפט ולא כהערה ──
//
// ההגנה הזו יושבת בדיוק על הגבול שאסור לטעות בו: מצד אחד קובץ נתונים שנקרא
// כהזמנה (רשימת לקוחות שהפכה ל-770 פריטים בהזמנה #10018), ומצד שני הזמנת רכש
// אמיתית שנחסמת בטעות. הניסוח הראשון של ההגנה עשה בדיוק את השנייה — הוא בדק
// גם את שורת המקור, ושורת טבלה מתומחרת ("גבינה לבנה  120  4.50  540.00")
// נראית לזיהוי הטלפון כרצף ספרות ארוך. הזמנה #10007 נחסמה בגלל זה.
//
// לכן כל שינוי בספים או בדפוסים חייב לעבור כאן — הסוללה מחזיקה את שני הקצוות
// יחד, וזה מה שהערה בקוד לא יכולה לעשות.
//
// אין תלות במסד ואין תלות ברשת.

const { notAnOrderTableReason } = require("../lib/order-ingestion/tableParser");

let passed = 0;
const failures = [];

const check = (label, items, shouldReject) => {
  const reason = notAnOrderTableReason(items);
  const rejected = Boolean(reason);
  if (rejected === shouldReject) {
    passed += 1;
    console.log(`  ✓ ${(rejected ? "נדחה" : "עובר").padEnd(5)} ${label}`);
  } else {
    failures.push(label);
    console.log(
      `  ✗ ${label}\n      ציפינו ל-${shouldReject ? "דחייה" : "מעבר"}, קיבלנו ${
        rejected ? `דחייה: ${reason}` : "מעבר"
      }`
    );
  }
};

const items = (names, qty = () => 1) =>
  names.map((rawName, i) => ({ rawName, quantity: qty(i) }));

// ── מה שחייב להידחות ──
console.log("\nקבצי נתונים שאינם הזמנה:");

check(
  "רשימת לקוחות: שם חברה + כתובת + טלפון + מייל",
  items([
    'אורט ישראל - המינהל למו"פ דרך הטיסים 28 תל-אביב טניה 03-6301378',
    "נובולוג פארם אפ המעין 55 מודיעין 0542349999 לאה 08-6604404",
    "סודקסקו MSD החרש 34 הוד השרון 0525522121 Dana.Moskovitz@sodexo.com",
    'אי.גי.אמ.די. בע"מ המסגר 39 תל אביב 03-6378600 ניקול 052-7466413',
    "מאיר חברה למכוניות חיים שפירא 25 ראשון לציון 03-9412345",
    "יוניסל פתרונות סלולריים ירושלים 39 קניון קרית אונו 03-5551234",
    "אהרון שרון מוסך מורשה הונדה ברקת 7 הרצליה 09-7778888",
    "גנסיס טורס המלאכה 6 חולון 03-6667777 ceciliah@genesis-tours.com",
  ]),
  true
);

check(
  'הכמויות הן מספרי שורה (1, 2, 3…)',
  items(
    ["חלב 3%", "לחם פרוס", "קוטג'", "ביצים", "גבינה צהובה", "יוגורט", "חמאה", "שמנת", "קפה", "סוכר"],
    (i) => i + 1
  ),
  true
);

check(
  "קובץ ענק — 400 שורות",
  items(Array.from({ length: 400 }, (_, i) => `מוצר ${i}`)),
  true
);

// ── מה שחייב לעבור ──
console.log("\nהזמנות אמיתיות:");

check(
  "הזמנת מכולת רגילה",
  items(
    [
      "גבינה לבנה 5% אישית",
      "קוטג אישי",
      "סחוג",
      "אפונת גינה קפואה בשקית",
      "טחינה אישי",
      "חומוס אישי",
      "לחם פרוס אחיד",
      'סוכר 1 ק"ג',
      "מלפפון קילו",
      "עגבנייה קילו",
    ],
    (i) => [120, 80, 4, 4, 80, 60, 8, 10, 8, 8][i]
  ),
  false
);

check(
  "הזמנה שהכמויות בה עולות אך אינן רצף",
  items(
    ["מוצר א", "מוצר ב", "מוצר ג", "מוצר ד", "מוצר ה", "מוצר ו", "מוצר ז", "מוצר ח", "מוצר ט"],
    (i) => [1, 2, 3, 4, 10, 20, 30, 40, 50][i]
  ),
  false
);

check(
  "הזמנה שכל הכמויות בה 1 — לא רצף רץ",
  items(
    ["כוסות חם", "נייר ידיים שישיה", "סבון כלים", "מפת שולחן חדפ", "מפות שולחן שקוף",
     "מגבונים", "שקיות אשפה", "כפיות", "צלחות", "מפיות"],
    () => 1
  ),
  false
);

check(
  "הזמנה סיטונאית גדולה — 140 שורות, מתחת לתקרה",
  items(Array.from({ length: 140 }, (_, i) => `מוצר ${i}`), (i) => (i % 7) + 1),
  false
);

check(
  "הזמנה קצרה שיש בה שם מוצר עם מספר ארוך",
  items(['נייר תעשייתי חי 1231', 'קפה עלית 200 גרם', 'סוכר 1 ק"ג'], () => 5),
  false
);

// ── הקצה: מתחת לסף המסה ──
console.log("\nמתחת לסף המסה — לא מכריעים על מעט שורות:");

check(
  "שלוש שורות שנראות כאנשי קשר",
  items(["a@b.co", "c@d.co", "מוצר"], (i) => i + 1),
  false
);

// ── סיכום ──
const total = passed + failures.length;
console.log(`\n${passed}/${total} עברו`);
if (failures.length) {
  console.log("\nנכשלו:");
  failures.forEach((f) => console.log(`  • ${f}`));
  process.exit(1);
}
