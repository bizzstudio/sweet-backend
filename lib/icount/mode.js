// lib/icount/mode.js
//
// מצב העבודה מול iCount: live (ברירת המחדל) או demo.
//
// למה זה קובץ נפרד ולא עוד תנאי ב-client.js:
//
//   ההבדל בין המצבים אינו רק "לאיזה חשבון מתחברים". במצב דמו אסור לכתוב
//   שום דבר למסד — לא לסמן תעודות כמחויבות, לא לשמור icountClientId של
//   חשבון אחר — ואסור להריץ את הסגירה החודשית. את הבדיקה הזאת עושים
//   מודולים שאינם מכירים את שכבת ה-HTTP (monthlyBilling, monthEndCron),
//   ולכן היא יושבת במקום שאין לו שום תלות.
//
// המצב נקבע פעם אחת בעליית התהליך. שינוי דורש ריסטארט — מכוון: מצב שמשתנה
// באמצע ריצה היה יכול להשאיר חצי סגירת חודש בחשבון אחד וחצי בשני.

const RAW_MODE = String(process.env.ICOUNT_MODE || "live").trim().toLowerCase();

const DEMO = RAW_MODE === "demo";

/** האם אנחנו מחוברים לחשבון דמו. */
const isDemoMode = () => DEMO;

/** "demo" או "live" — לתצוגה בממשק ובלוגים. */
const modeLabel = () => (DEMO ? "demo" : "live");

/*
 * אין כאן assertNotDemo.
 *
 * היה, ונמחק ב-18/08/26 כשמצב הדמו קיבל כיס חיוב משלו על התעודה
 * (lib/billing/ledger.js). מרגע שכל כתיבה בדמו הולכת ל-billing.demo,
 * אין יותר פעולה שצריך לחסום כדי להגן על הרישום האמיתי — סגירת חודש,
 * זיכוי ורישום תשלום כולם בטוחים.
 *
 * מה שכן נשאר מחוץ לדמו הוא הסגירה האוטומטית של סוף החודש, והיא בודקת
 * isDemoMode() ישירות (lib/billing/monthEndCron.js). הסיבה שונה: היא
 * רצה בלילה בלי אדם, ובדמו הייתה מחייבת לכיס הדמו בלבד — כלומר החודש
 * האמיתי היה נשאר פתוח בלי שאיש יידע.
 */

/**
 * ההפך: פעולה שקיימת רק במצב דמו (המסלולים של מסך ההדגמה).
 * בלי זה, שכחה של ICOUNT_MODE=demo בפרודקשן הייתה הופכת את כפתור
 * "הפק חשבונית דמו" למכונה להפקת חשבוניות מס אמיתיות.
 */
const assertDemo = (action) => {
  if (DEMO) return;
  throw new Error(
    `${action} זמין רק כש-ICOUNT_MODE=demo. כרגע המערכת מחוברת לחשבון האמיתי.`
  );
};

module.exports = { isDemoMode, modeLabel, assertDemo };
